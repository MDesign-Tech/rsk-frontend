export function Footer() {
  const data = useWebsiteStore((state) => state.data);

  const about = data?.about;
  const services = (data?.services ?? []).filter(
    (service) => service.visible !== false,
  );

  const socialMedia = about?.socialMedia;
  const socialLinks = SOCIAL_PLATFORMS.map((platform) => {
    const entry = socialMedia?.[platform];
    return {
      platform,
      href: entry?.href ?? null,
      visible: entry?.visible ?? true,
    };
  }).filter((item) => item.visible && item.href);

  return (
    <footer className="relative border-t border-border">
      <div className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 py-12 sm:py-16">
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-8 mb-12">
          {/* Company Info */}
          <div>
            <Link href="/" className="flex items-center gap-3 mb-4">
              <Image
                src="/rsk-logo.svg"
                alt="RSK Associates"
                width={80}
                height={80}
                className="w-20 h-auto"
              />
              <span
                className="font-bold text-foreground text-xs"
                style={{ letterSpacing: "-0.05em" }}
              >
                RSK
              </span>
            </Link>
            <p className="text-xs sm:text-sm text-muted-foreground mb-4">
              Trusted partners in audit, tax advisory, and financial consulting.
            </p>
            <div className="space-y-2">
              {about?.contactMethods
                ?.filter((item) => item.visible !== false)
                .map((item, index) => {
                const Icon = getContactIcon(item.label);

                return (
                  <div
                    key={index}
                    className="flex items-start gap-2 text-xs text-muted-foreground"
                  >
                    <Icon className="w-4 h-4 mt-0.5 flex-shrink-0" />

                    {item.href ? (
                      <a
                        href={item.href}
                        className="hover:text-foreground transition-colors"
                      >
                        {item.value}
                      </a>
                    ) : (
                      <span>{item.value}</span>
                    )}
                  </div>
                );
              })}
            </div>
          </div>

          {/* Services */}
          <div>
            <h4 className="text-xs font-medium tracking-wider uppercase text-muted-foreground mb-4">
              Services
            </h4>
            <ul className="space-y-2">
              {services.map((service) => (
                <li key={service._id}>
                  <a
                    href="#our-services"
                    className="text-xs sm:text-sm text-muted-foreground hover:text-foreground transition-colors"
                  >
                    {service.title}
                  </a>
                </li>
              ))}
            </ul>
          </div>

          {/* Link columns */}
          {Object.entries(footerLinks).map(([category, links]) => (
            <div key={category}>
              <h4 className="text-xs font-medium tracking-wider uppercase text-muted-foreground mb-4">
                {category}
              </h4>
              <ul className="space-y-2">
                {links.map((link) => (
                  <li key={link.label}>
                    <Link
                      href={link.href}
                      className="text-xs sm:text-sm text-muted-foreground hover:text-foreground transition-colors"
                    >
                      {link.label}
                    </Link>
                  </li>
                ))}
              </ul>
            </div>
          ))}
        </div>

        <div className="pt-8 border-t border-border flex flex-col sm:flex-row items-center justify-between gap-4">
          <p className="text-[10px] sm:text-xs text-muted-foreground">
            &copy; {new Date().getFullYear()} RSK Associates. All rights
            reserved.
          </p>
          <div className="flex items-center gap-6">
            {socialLinks.map(({ platform, href }) => (
              <Link
                key={platform}
                href={href as string}
                target="_blank"
                rel="noopener noreferrer"
                className="text-muted-foreground hover:text-foreground transition-colors"
                aria-label={platform}
              >
                <svg
                  className="w-4 sm:w-5 h-4 sm:h-5"
                  fill="currentColor"
                  viewBox="0 0 24 24"
                  aria-hidden="true"
                >
                  {SOCIAL_ICONS[platform]}
                </svg>
              </Link>
            ))}
          </div>
        </div>
      </div>
    </footer>
  );
}
